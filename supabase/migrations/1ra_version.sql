);

-- 6. SURTIDOR
CREATE TABLE surtidor (
    id_surtidor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion BIGINT NOT NULL REFERENCES estacion(id_estacion),
    numero INTEGER NOT NULL CHECK (numero > 0),
    tipo_combustible VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    UNIQUE (id_estacion, numero),
    UNIQUE (id_surtidor, id_estacion)
);

-- 7. OPERADOR
CREATE TABLE operador (
    id_operador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion BIGINT NOT NULL REFERENCES estacion(id_estacion),
    ci VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    usuario VARCHAR(60) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    UNIQUE (id_operador, id_estacion)
);

-- 8. CARGA_COMBUSTIBLE
CREATE TABLE carga_combustible (
    id_carga BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL REFERENCES persona(id_persona),
    id_vehiculo BIGINT NOT NULL,
    id_estacion BIGINT NOT NULL REFERENCES estacion(id_estacion),
    id_surtidor BIGINT NOT NULL,
    id_operador BIGINT NOT NULL,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    litros NUMERIC(10,2) NOT NULL CHECK (litros > 0),
    litros_subvencionados NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (litros_subvencionados >= 0),
    litros_precio_internacional NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (litros_precio_internacional >= 0),
    monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'registrada',
    CONSTRAINT chk_carga_desglose CHECK (
        litros = litros_subvencionados + litros_precio_internacional
    ),
    -- Evitan registrar propietario, surtidor u operador de otro contexto.
    CONSTRAINT fk_carga_vehiculo_persona FOREIGN KEY (id_vehiculo, id_persona)
        REFERENCES vehiculo(id_vehiculo, id_persona),
    CONSTRAINT fk_carga_surtidor_estacion FOREIGN KEY (id_surtidor, id_estacion)
        REFERENCES surtidor(id_surtidor, id_estacion),
    CONSTRAINT fk_carga_operador_estacion FOREIGN KEY (id_operador, id_estacion)
        REFERENCES operador(id_operador, id_estacion),
    UNIQUE (id_carga, id_vehiculo)
);

-- 9. BLOQUEO
CREATE TABLE bloqueo (
    id_bloqueo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL REFERENCES persona(id_persona),
    id_vehiculo BIGINT NOT NULL REFERENCES vehiculo(id_vehiculo),
    motivo TEXT NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    CONSTRAINT chk_bloqueo_fechas CHECK (
        fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    )
);

-- 10. ALERTA
CREATE TABLE alerta (
    id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carga BIGINT NOT NULL,
    id_vehiculo BIGINT NOT NULL,
    tipo_alerta VARCHAR(80) NOT NULL,
    descripcion TEXT NOT NULL,
    nivel VARCHAR(20) NOT NULL DEFAULT 'medio',
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    CONSTRAINT fk_alerta_carga_vehiculo FOREIGN KEY (id_carga, id_vehiculo)
        REFERENCES carga_combustible(id_carga, id_vehiculo)
);

